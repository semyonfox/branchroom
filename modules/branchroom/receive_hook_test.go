package branchroom

import (
	"strings"
	"testing"

	"gitea.dev/modules/setting"

	"github.com/stretchr/testify/assert"
)

func setHookSettings(t *testing.T, scriptType, appPath, customConf string) {
	t.Helper()
	origScriptType, origAppPath, origCustomConf := setting.ScriptType, setting.AppPath, setting.CustomConf
	setting.ScriptType = scriptType
	setting.AppPath = appPath
	setting.CustomConf = customConf
	t.Cleanup(func() {
		setting.ScriptType = origScriptType
		setting.AppPath = origAppPath
		setting.CustomConf = origCustomConf
	})
}

func TestReceivePreReceiveHookTemplate(t *testing.T) {
	t.Run("ordinary", func(t *testing.T) {
		setHookSettings(t, "sh", "/usr/local/bin/gitea", "/etc/gitea/app.ini")

		assert.Equal(t, `#!/usr/bin/env sh
# AUTO GENERATED BY GITEA, DO NOT MODIFY
exec /usr/local/bin/gitea hook --config=/etc/gitea/app.ini branchroom-pre-receive
`, ReceivePreReceiveHookTemplate())
	})

	t.Run("hostile", func(t *testing.T) {
		setHookSettings(t, "sh", "/opt/Gitea Server/gitea$bin", "/etc/gitea/conf;rm -rf /")

		output := ReceivePreReceiveHookTemplate()
		assert.Equal(t, `#!/usr/bin/env sh
# AUTO GENERATED BY GITEA, DO NOT MODIFY
exec "/opt/Gitea Server/gitea\$bin" hook --config="/etc/gitea/conf;rm -rf /" branchroom-pre-receive
`, output)
		for _, forbidden := range []string{
			"GITEA_BRANCHROOM_RECEIVE_SESSION_KEY",
			"GITEA_BRANCHROOM_RECEIVE_BEARER_SECRET",
			"refs/",
			".git/",
		} {
			assert.NotContains(t, output, forbidden)
		}
		assert.True(t, strings.HasSuffix(output, "\n"))
	})
}
